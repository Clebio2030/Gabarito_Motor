    a.TOTALPG,
    CAST(c.RECEBTO     AS VARCHAR(50)  CHARACTER SET OCTETS) AS FORMARECEBIDA,
    CAST(d.RECEBTO     AS VARCHAR(50)  CHARACTER SET OCTETS) AS FORMAPAGA,
    a.STATUS,
    CAST(e.NOMEEMPRESA AS VARCHAR(60)  CHARACTER SET OCTETS) AS NOMEEMPRESA,
    CAST(f.VENDEDOR    AS VARCHAR(50)  CHARACTER SET OCTETS) AS VENDEDOR,
    g.CDCLIENTE,
    CAST(g.CLIENTE     AS VARCHAR(100) CHARACTER SET OCTETS) AS CLIENTE,
    a.CAIXA                     AS CDCAIXA,
    a.PARCELA,
