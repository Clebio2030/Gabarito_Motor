    LEFT JOIN SAIDAESTOQUE     b ON (a.IDEMPRESA  = b.IDEMPRESA)
                                AND (a.NRPEDIDO   = b.NRPEDIDO)
    LEFT JOIN RECEBTO          c ON (a.CODPAGTO   = c.CDRECEBTO)
    LEFT JOIN RECEBTO          d ON (a.TPPAGTO    = d.CDRECEBTO)
